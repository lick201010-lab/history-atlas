function closeRing(points) {
  if (!Array.isArray(points) || points.length < 3) {
    throw new Error('Ring must contain at least three points.');
  }
  const closed = points.map(([lng, lat]) => [lng, lat]);
  const first = closed[0];
  const last = closed.at(-1);
  if (first[0] !== last[0] || first[1] !== last[1]) closed.push([...first]);
  return closed;
}

function idOf(feature) {
  return feature.properties?.id || feature.id;
}

function geometryFromDefinition(definition) {
  if (definition.polygons) {
    return {
      type: 'MultiPolygon',
      coordinates: definition.polygons.map((polygon) => [closeRing(polygon)]),
    };
  }

  return {
    type: 'Polygon',
    coordinates: [closeRing(definition.ring)],
  };
}

function outerRings(geometry) {
  if (geometry.type === 'Polygon') return [geometry.coordinates[0]];
  return geometry.coordinates.map((polygon) => polygon[0]);
}

function makeFeature(base, definition) {
  const geometry = geometryFromDefinition(definition);
  return {
    type: 'Feature',
    properties: {
      id: base.id,
      dynasty: base.dynasty,
      phase: definition.phase,
      phaseLabel: definition.phaseLabel,
      startYear: definition.startYear,
      endYear: definition.endYear,
      color: base.color,
      capital: base.capital,
      summary: definition.summary,
      accuracy: definition.accuracy,
      accuracyLabel: definition.accuracy === 'coastline-aware-rough' ? '海岸贴合粗精修' : '粗精修示意范围',
      accuracyNote: notes[base.id].accuracyNote,
      sourceNote: notes[base.id].sourceNote,
    },
    geometry,
  };
}

function assertGenerated(features) {
  for (const id of batchIds) {
    const group = features.filter((feature) => idOf(feature) === id).sort((a, b) => a.properties.startYear - b.properties.startYear);
    if (group.length !== 3) throw new Error(`${id} must have exactly 3 features.`);
    for (const phase of phases) {
      if (!group.some((feature) => feature.properties.phase === phase)) throw new Error(`${id} missing phase ${phase}.`);
    }
    for (let index = 1; index < group.length; index += 1) {
      if (group[index].properties.startYear !== group[index - 1].properties.endYear + 1) {
        throw new Error(`${id} phases are not contiguous.`);
      }
    }
    for (const feature of group) {
      if (!feature.properties.sourceNote || !feature.properties.accuracyNote) {
        throw new Error(`${id} feature missing sourceNote or accuracyNote.`);
      }
      const rings = outerRings(feature.geometry);
      const totalVertices = rings.reduce((sum, ring) => sum + ring.length, 0);
      if (feature.properties.accuracy === 'coastline-aware-rough') {
        if (feature.geometry.type === 'Polygon' && rings[0].length < 40) throw new Error(`${id} coastline-aware polygon has too few vertices.`);
        if (feature.geometry.type === 'MultiPolygon' && totalVertices < 80) throw new Error(`${id} coastline-aware multipolygon has too few vertices.`);
      } else if (rings[0].length < 21) {
        throw new Error(`${id} rough-refined polygon has too few vertices.`);
      }
    }
  }
}

