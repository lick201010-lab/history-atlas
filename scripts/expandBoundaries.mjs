const ACCURACY_LABEL = '粗略多边形';
const ACCURACY = 'rough-refined';
const ACCURACY_NOTE = '此边界为粗略多边形示意，比矩形更贴近历史轮廓，但仍用于沙盘视觉与交互演示，不代表精确历史疆域。';

const data = JSON.parse(await readFile(DATA_PATH, 'utf8'));
let updated = 0;
const missing = [];

for (const feature of data.features) {
  const id = feature.properties?.id;
  if (SAMPLE_IDS.has(id)) continue;
  const ring = RINGS[id];
  const note = SOURCE_NOTES[id];
  if (!ring || !note) { missing.push(id); continue; }

  // Sanity guard: ring closed, ≥7 points, not rectangle-like.
  if (ring.length < 7) throw new Error(`${id}: ring too short (${ring.length})`);
  const first = ring[0];
  const last = ring[ring.length - 1];
  if (first[0] !== last[0] || first[1] !== last[1]) throw new Error(`${id}: ring not closed`);
  const uniqueLng = new Set(ring.map((p) => p[0]));
  const uniqueLat = new Set(ring.map((p) => p[1]));
  if (uniqueLng.size <= 2 && uniqueLat.size <= 2) throw new Error(`${id}: ring is rectangle-like`);
  for (const [lng, lat] of ring) {
    if (lng < -180 || lng > 180 || lat < -90 || lat > 90) throw new Error(`${id}: coord out of range`);
  }

  feature.geometry = { type: 'Polygon', coordinates: [ring] };
  feature.properties.accuracy = ACCURACY;
  feature.properties.accuracyLabel = ACCURACY_LABEL;
  feature.properties.accuracyNote = ACCURACY_NOTE;
  feature.properties.sourceNote = note;
  updated++;
}

if (missing.length > 0) {
  console.error('Missing ring/note for:', missing);
  process.exit(1);
}

await writeFile(DATA_PATH, JSON.stringify(data, null, 2) + '\n', 'utf8');
console.log(`Refined ${updated} boundaries.`);
